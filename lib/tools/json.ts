export interface JsonStats {
  characters: number;
  lines: number;
  bytes: number;
  keyCount: number;
  maxDepth: number;
  type: 'object' | 'array' | 'primitive';
}

export interface JsonValidationResult {
  isValid: boolean;
  error?: {
    message: string;
    line?: number;
    column?: number;
  };
  stats?: JsonStats;
}

export function validateJson(input: string): JsonValidationResult {
  const trimmed = input.trim();
  if (!trimmed) {
    return { isValid: false, error: { message: 'Input is empty' } };
  }

  try {
    const parsed = JSON.parse(trimmed);
    const stats = calculateJsonStats(parsed, trimmed);
    return { isValid: true, stats };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Invalid JSON format';
    const position = extractErrorPosition(message, trimmed);
    return {
      isValid: false,
      error: {
        message,
        line: position?.line,
        column: position?.column,
      },
    };
  }
}

function extractErrorPosition(errorMessage: string, text: string): { line: number; column: number } | undefined {
  // Regex patterns commonly generated by V8 / SpiderMonkey JSON.parse
  // e.g., "Unexpected token '}' at line 3 column 5 of the JSON data"
  // or "Unexpected token '}' at position 42"
  const lineColMatch = errorMessage.match(/line (\d+) column (\d+)/i);
  if (lineColMatch) {
    return {
      line: parseInt(lineColMatch[1], 10),
      column: parseInt(lineColMatch[2], 10),
    };
  }

  const posMatch = errorMessage.match(/position (\d+)/i);
  if (posMatch) {
    const pos = parseInt(posMatch[1], 10);
    const lines = text.slice(0, pos).split('\n');
    return {
      line: lines.length,
      column: lines[lines.length - 1].length + 1,
    };
  }

  return undefined;
}

export function formatJson(
  input: string,
  indent: number | string = 2,
  sortKeys = false
): { formatted: string; error?: string; stats?: JsonStats } {
  const trimmed = input.trim();
  if (!trimmed) {
    return { formatted: '', error: 'Please enter JSON text' };
  }

  try {
    let parsed = JSON.parse(trimmed);
    if (sortKeys) {
      parsed = sortObjectKeys(parsed);
    }
    const indentValue = indent === 'tab' ? '\t' : Number(indent);
    const formatted = JSON.stringify(parsed, null, indentValue);
    const stats = calculateJsonStats(parsed, formatted);
    return { formatted, stats };
  } catch (err: unknown) {
    return {
      formatted: input,
      error: err instanceof Error ? err.message : 'Invalid JSON format',
    };
  }
}

export function minifyJson(input: string): { minified: string; error?: string; stats?: JsonStats } {
  const trimmed = input.trim();
  if (!trimmed) {
    return { minified: '', error: 'Please enter JSON text' };
  }

  try {
    const parsed = JSON.parse(trimmed);
    const minified = JSON.stringify(parsed);
    const stats = calculateJsonStats(parsed, minified);
    return { minified, stats };
  } catch (err: unknown) {
    return {
      minified: input,
      error: err instanceof Error ? err.message : 'Invalid JSON format',
    };
  }
}

export function sortObjectKeys(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(sortObjectKeys);
  } else if (value !== null && typeof value === 'object') {
    const sortedObj: Record<string, unknown> = {};
    const keys = Object.keys(value as Record<string, unknown>).sort();
    for (const key of keys) {
      sortedObj[key] = sortObjectKeys((value as Record<string, unknown>)[key]);
    }
    return sortedObj;
  }
  return value;
}

function calculateJsonStats(parsed: unknown, text: string): JsonStats {
  let keyCount = 0;
  let maxDepth = 0;

  function traverse(node: unknown, depth: number) {
    if (depth > maxDepth) maxDepth = depth;
    if (Array.isArray(node)) {
      for (const item of node) {
        traverse(item, depth + 1);
      }
    } else if (node !== null && typeof node === 'object') {
      const keys = Object.keys(node as object);
      keyCount += keys.length;
      for (const key of keys) {
        traverse((node as Record<string, unknown>)[key], depth + 1);
      }
    }
  }

  traverse(parsed, 1);

  return {
    characters: text.length,
    lines: text.split('\n').length,
    bytes: new TextEncoder().encode(text).length,
    keyCount,
    maxDepth,
    type: Array.isArray(parsed) ? 'array' : typeof parsed === 'object' && parsed !== null ? 'object' : 'primitive',
  };
}

